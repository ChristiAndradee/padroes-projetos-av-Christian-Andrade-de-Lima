public class SolicitacaoAmbiente {

    public String nomeAmbiente;
    public int quantidadeMaquinas;
    public int gbArmazenamento;

    public SolicitacaoAmbiente(String nomeAmbiente, int quantidadeMaquinas, int gbArmazenamento) {
        this.nomeAmbiente = nomeAmbiente;
        this.quantidadeMaquinas = quantidadeMaquinas;
        this.gbArmazenamento = gbArmazenamento;
    }
}
